const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const vm=require('node:vm');
const source=fs.readFileSync('lib/backend/adapters/oracle/marketplace-write-adapter.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};
vm.runInNewContext(js,{module:mod,exports:mod.exports,require});
const ID='33333333-3333-4333-8333-333333333333';
const USER='11111111-1111-4111-8111-111111111111';
const record={id:ID,status:'active',title:'Book',categoryId:null,city:'Cairo',area:null,condition:'good_used',conditionNotes:null,description:null,itemStory:null,swapReason:null,goodFor:null,desireMode:'flexible',desireText:null,wantedTags:['art']};
const images={itemId:ID,title:'Book',status:'active',images:[{id:ID,imageUrl:'https://example.test/a.jpg',isPrimary:true,sortOrder:0,createdAt:null}]};
(async()=>{
  let call; let response={ok:true,status:200,data:record};
  const adapter=mod.exports.createOracleMarketplaceWriteAdapter({request:async input=>{call=input;return response;}});
  assert.equal((await adapter.getEditableListing(ID,USER)).title,'Book');
  assert.equal(call.path,`/v1/marketplace/items/${ID}/edit`);
  assert.equal(call.body,undefined);
  response={ok:true,status:200,data:images};
  assert.equal((await adapter.getEditableListingImagesContext(ID,USER)).images.length,1);
  assert.equal(call.path,`/v1/marketplace/items/${ID}/edit/images`);
  response={ok:false,status:404,reason:'not_found',retryable:false};
  assert.equal(await adapter.getEditableListing(ID,USER),null);
  response={ok:true,status:200,data:{...record,wantedTags:null}};
  await assert.rejects(()=>adapter.getEditableListing(ID,USER));
  response={ok:true,status:200,data:{ok:true,code:'updated'}};
  const input={itemId:ID,ownerId:USER,title:'New'};
  assert.equal((await adapter.updateListingCore(input)).ok,true);
  assert.equal(call.method,'POST');
  assert.equal(call.body,input);
  response={ok:true,status:200,data:{ok:false,code:'not_editable'}};
  assert.equal((await adapter.updateListingCore(input)).reason,'not_editable');
  response={ok:true,status:200,data:{ok:false,code:'not_found_or_unauthorized'}};
  assert.equal((await adapter.updateListingCore(input)).reason,'not_found_or_unauthorized');
  response={ok:false,status:409,reason:'conflict',retryable:false};
  assert.equal((await adapter.updateListingCore(input)).reason,'unknown');
  response={ok:true,status:200,data:{ok:true,code:'unexpected'}};
  assert.equal((await adapter.updateListingCore(input)).reason,'unknown');
  process.stdout.write('oracle_marketplace_edit_adapter=PASS\n');
})().catch(error=>{console.error(error);process.exitCode=1;});
