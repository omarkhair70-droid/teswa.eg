const fs=require('fs'),ts=require('typescript'),vm=require('vm');
let src=fs.readFileSync('lib/backend/adapters/oracle/direct-messaging-adapter.ts','utf8').replace(/^import type[\s\S]*?from '[^']+';\r?\n/gm,'');
const js=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};vm.runInNewContext(js,{module:mod,exports:mod.exports,require,Array,Boolean,Error,String});
(async()=>{const calls=[];const t={request:async input=>{calls.push(input);
 if(input.path==='/v1/direct/conversations')return{ok:true,status:200,data:{items:[]}};
 if(input.path.endsWith('/typing')&&input.method!=='POST')return{ok:true,status:200,data:{userIds:['other']}};
 if(input.path.endsWith('/reaction'))return{ok:true,status:200,data:{ok:true,enabled:true,count:1}};
 if(input.path.endsWith('/native'))return{ok:true,status:200,data:{ok:true,message:'sent',messageId:'message',createdAt:'now'}};
 return{ok:true,status:200,data:{ok:true,conversationId:'conversation',status:'accepted',requiresRequest:false,message:'ok'}};
 }};
 const a=mod.exports.createOracleDirectMessagingAdapter(t);
 if(!(await a.startOrGet('other')).ok)throw Error('start');
 if(!(await a.listConversations()).ok)throw Error('list');
 const typing=await a.listNativeTypingUsers('conversation');if(!typing.ok||typing.data[0]!=='other')throw Error('typing');
 const reaction=await a.toggleNativeReaction('message','love');if(!reaction.ok||reaction.data.count!==1)throw Error('reaction');
 const sent=await a.sendNativeMessage({conversationId:'conversation',attachments:[],metadata:{}});if(!sent.ok)throw Error('native');
 if(calls.some(c=>c.body&&Object.hasOwn(c.body,'userId')))throw Error('client actor forwarded');
 process.stdout.write('oracle_direct_messaging_adapter=PASS\n');
})().catch(e=>{console.error(e);process.exit(1)});
